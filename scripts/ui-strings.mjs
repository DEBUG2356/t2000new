import fs from "node:fs";
import path from "node:path";
import * as cheerio from "cheerio";
const dir = path.resolve("_archive");
const survey = JSON.parse(fs.readFileSync(path.join(dir, "survey.json"), "utf8"));
const index = JSON.parse(fs.readFileSync(path.join(dir, "index.json"), "utf8"));
const res = {};
const t = (s) => s.replace(/\s+/g, " ").trim();
for (const s of survey) {
  const $ = cheerio.load(fs.readFileSync(path.join(dir, "raw", index[s.key].file), "utf8"));
  const L = s.lang;
  const r = (res[L] ||= {});
  const put = (k, v) => { v = t(v || ""); if (v && !r[k]) r[k] = v; };
  $(".module-header").each((i, e) => put("h:" + t($(e).text()).slice(0, 30), $(e).text() + " || " + $(e).next().text()));
  put("readmore", $(".readmore-wrap").first().text());
  put("checkAvail", $(".check-availability-wrap a, .check-availability-wrap button").first().text());
  put("viewAll", $(".btn-outline-secondary").first().text());
  $(".properties-wrap span:not(.image-wrap)").each((i, e) => put("prop" + i, $(e).text()));
  put("price", $(".price-wrap").first().text());
  put("services", $(".services .name").map((i, e) => $(e).text()).get().join(" | "));
  put("share", $(".share-btn").first().text());
  put("buyNow", $("#buyYourTicket").text());
  put("maps", $('#locationCollapse a.btn').text());
  put("reviewsTitle", $("#reviews .tag-h1").first().text());
  put("bars", $(".ratings .bars .col:first-child").map((i, e) => $(e).text()).get().join(" | "));
  put("reviewsWord", $(".ratings .total").next().text());
  put("upsell", $(".product-full-wrap").find(".module-header, .tag-h3, h3").map((i, e) => $(e).text()).get().join(" | "));
  put("related", $(".related-products .module-header, .upsell-products-wrap h3").first().text());
  put("footer", $("footer").text());
  put("newsletter", $(".module-newsletter input, .newsletter input").map((i, e) => $(e).attr("placeholder") || $(e).attr("value")).get().join(" | ") + " || " + $(".module-newsletter label, .newsletter label").text());
  put("why", $(".module-articles").first().text());
  put("cookie", $("[class*=gdpr], #gdpr-cookie-message").first().text());
  put("searchPh", $('input[type="search"], input[name="q"], input[name="search"]').first().attr("placeholder"));
  put("sorting", $(".sorting, .sort-by, select[name=sort]").first().text());
  put("hero", $(".slider, .carousel, .module-slider").first().text());
  put("catHead", $(".category-header-title").first().text());
  if (s.type === "contact") put("contact", $("main, .content-wrap").first().text());
  if (s.type === "search") put("search", $("main, .content-wrap").first().text());
  put("nav", $("nav .navbar-nav").first().text());
  put("back", $("a.btn:contains('Back'), .btn-back").first().text());
  put("seeMore", $(".seemore").first().text());
  put("contentsPkg", $(".product-full .tag-h1").first().text());
}
fs.writeFileSync(path.join(dir, "ui-strings.json"), JSON.stringify(res, null, 1));
